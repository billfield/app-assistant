    private val GEOMETRY_SPEC_EXAMPLE = """
如果题目涉及几何图形（如三角形、圆、坐标系、函数图像、几何体等），必须在"几何图形"字段中输出符合以下协议的结构化 JSON（不是 Python 代码）。这是强制要求；纯代数题可填 null。

协议格式（GeometrySpec）：
{
  "points": {"A": [x1, y1], "B": [x2, y2], ...},
  "primitives": [
    {"type": "polygon", "vertices": ["A", "B", "C"]},
    {"type": "segment", "p1": "A", "p2": "B"},
    {"type": "circle", "center": "A", "radius": 1.0},
    {"type": "angle", "vertex": "B", "from": "A", "to": "C", "label": "60°"},
    {"type": "label", "at": "A", "text": "A", "offset": [0, 0.15]}
  ],
  "view": {"equal": true, "showAxes": false}
}

字段说明：
- points: 命名坐标，key 是点的标签（如 "A"），value 是 [x, y]
- primitives: 绘图元素数组，按绘制顺序给出
- polygon: 多边形，vertices 是点的标签数组
- segment: 线段，p1/p2 是点标签
- circle: 圆，center 是圆心标签，radius 是半径数值
- angle: 角标记，vertex 是顶点，from/to 是两边的端点
- label: 文本标签，at 是参考点，offset 是相对偏移
- view: equal=true 保持等比例，showAxes=false 隐藏坐标轴

示例 1（等边三角形 ABC）：
{
  "points": {"A": [0, 1.732], "B": [-1, 0], "C": [1, 0]},
  "primitives": [
    {"type": "polygon", "vertices": ["A", "B", "C"]},
    {"type": "label", "at": "A", "text": "A", "offset": [0, 0.15]},
    {"type": "label", "at": "B", "text": "B", "offset": [-0.15, -0.1]},
    {"type": "label", "at": "C", "text": "C", "offset": [0.15, -0.1]}
  ],
  "view": {"equal": true, "showAxes": false}
}

示例 2（圆和圆上一点 P）：
{
  "points": {"O": [0, 0], "P": [1, 0]},
  "primitives": [
    {"type": "circle", "center": "O", "radius": 1.0},
    {"type": "segment", "p1": "O", "p2": "P"},
    {"type": "label", "at": "O", "text": "O", "offset": [-0.15, -0.15]},
    {"type": "label", "at": "P", "text": "P", "offset": [0.15, 0]}
  ],
  "view": {"equal": true, "showAxes": false}
}

示例 3（一次函数 y = 2x + 1 图像，用多边形近似线段）：
{
  "points": {"A": [-2, -3], "B": [2, 5], "O": [0, 0]},
  "primitives": [
    {"type": "segment", "p1": "A", "p2": "B"},
    {"type": "label", "at": "O", "text": "O", "offset": [-0.2, -0.2]}
  ],
  "view": {"equal": true, "showAxes": true}
}

注意：
- 点的坐标数值用 JSON 数字（不要字符串）
- 所有点必须在 points 中声明后才能被 primitives 引用
- 不要在 primitives 中使用未在 points 中定义的标签
- 标签文本用纯文本（如 "A"），不要用 LaTeX
""".trimIndent()

